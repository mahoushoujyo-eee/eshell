// Ordered so the more specific product name wins: "OpenCode" must not read as
// OpenAI, and "Claude Code" must not read as OpenCode.
const BRAND_PATTERNS = [
  ["opencode", /opencode/],
  ["claude", /claude|anthropic/],
  ["openai", /codex|openai|chatgpt/],
  ["gemini", /gemini/],
  ["qwen", /qwen|tongyi/],
];

const haystack = (...parts) =>
  parts
    .filter((part) => typeof part === "string" && part.length > 0)
    .join(" ")
    .toLowerCase();

const firstMatch = (text) => {
  if (!text) {
    return null;
  }
  const hit = BRAND_PATTERNS.find(([, pattern]) => pattern.test(text));
  return hit ? hit[0] : null;
};

/**
 * Brand id for one agent config, or null when nothing matches. Identity
 * (id/name) wins over the spawn command so an explicitly named agent is never
 * mislabeled by an unrelated wrapper script.
 */
export function resolveAcpAgentBrandKey(agent) {
  if (!agent) {
    return null;
  }
  const identity = haystack(agent.id, agent.name);
  const spawn = haystack(agent.command, ...(Array.isArray(agent.args) ? agent.args : []));
  return firstMatch(identity) || firstMatch(spawn);
}

/** Brand metadata for one agent config (with its `key`), or null when unknown. */
export function getAcpAgentBrand(agent) {
  const key = resolveAcpAgentBrandKey(agent);
  return key ? { key, ...ACP_AGENT_BRANDS[key] } : null;
}

/** Full spawn command line for an agent; used as list subtitle and tooltip. */
export function formatAcpAgentSpawn(agent) {
  if (!agent) {
    return "";
  }
  const args = Array.isArray(agent.args) ? agent.args : [];
  return [agent.command, ...args].filter(Boolean).join(" ");
}
